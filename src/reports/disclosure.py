"""
Mandatory disclosures and data-provenance strings, in one place.

Why this module exists: the SEBI disclaimer used to live only as a line in an LLM
system prompt ("End investment-recommendation answers with: Not SEBI-registered
advice."). A model is free to drop that line, which would leave a buy/sell verdict
in front of an Indian retail investor with no disclosure attached. Anything that
must appear is therefore generated in code here and injected by the PDF, DOCX and
web renderers, so it cannot be omitted by a model's choice of words.

The provenance block exists for a related reason: a report that silently rests on
five-month-old fundamentals or a hardcoded risk-free rate looks exactly like one
built on live data. Every rendered artefact states which it is.
"""
from __future__ import annotations

from datetime import datetime
from typing import Any, Optional

# The disclosure that must appear on every generated artefact.
SEBI_DISCLAIMER = (
    "This report is generated by an automated research tool for educational and "
    "informational purposes only. It is not investment advice, and its author is "
    "not registered with SEBI as an Investment Adviser or Research Analyst. "
    "Nothing here is a recommendation to buy, sell or hold any security. "
    "Valuations are model estimates that depend heavily on assumptions and may be "
    "wrong. Past performance does not indicate future results. Consult a "
    "SEBI-registered adviser before investing."
)

# Short form, for places with no room for the full text (page footers, UI chrome).
SEBI_DISCLAIMER_SHORT = (
    "Educational use only — not investment advice; not SEBI-registered. "
    "Model estimates may be wrong."
)

AI_CONTENT_NOTICE = (
    "Narrative sections of this report were drafted by a large language model from "
    "the retrieved financial data shown. LLMs can state figures confidently and "
    "still be wrong — verify any number you intend to act on against the company's "
    "filings."
)


def data_provenance(
    rf_label: str = "",
    rf_is_live: bool = True,
    fundamentals_as_of: Optional[str] = None,
    fundamentals_age_days: Optional[float] = None,
    price_as_of: Optional[str] = None,
    stale_threshold_days: int = 90,
) -> list[str]:
    """
    Build the provenance lines for a report footer.

    Returns a list of plain strings so each renderer can lay them out its own way.
    Staleness is called out explicitly rather than left for the reader to infer.
    """
    lines: list[str] = [
        f"Report generated: {datetime.now().strftime('%d %b %Y, %H:%M IST')}"
    ]

    if fundamentals_as_of:
        line = f"Fundamentals (Screener.in): as of {fundamentals_as_of}"
        if fundamentals_age_days is not None:
            line += f" ({fundamentals_age_days:.0f} days old)"
            if fundamentals_age_days > stale_threshold_days:
                line += " — STALE: older than one reporting quarter"
        lines.append(line)

    if price_as_of:
        lines.append(f"Market price: {price_as_of}")

    if rf_label:
        line = f"Risk-free rate (India 10Y GSEC): {rf_label}"
        if not rf_is_live:
            line += " — NOT LIVE: valuation rests on a hardcoded rate"
        lines.append(line)

    lines.append("Sources: Screener.in, NSE India, Yahoo Finance.")
    return lines


def provenance_from_result(dcf_result: Any, freshness: Optional[dict] = None) -> list[str]:
    """Convenience wrapper: pull provenance straight off a DCFResult plus freshness dict."""
    freshness = freshness or {}
    return data_provenance(
        rf_label=getattr(dcf_result, "rf_label", "") or "",
        rf_is_live=bool(getattr(dcf_result, "rf_is_live", True)),
        fundamentals_as_of=freshness.get("last_modified"),
        fundamentals_age_days=freshness.get("age_days"),
    )


def is_report_trustworthy(dcf_result: Any, freshness: Optional[dict] = None) -> tuple[bool, list[str]]:
    """
    Whether a report rests on data fresh enough to be relied on.

    Returns (ok, warnings). Callers surface the warnings rather than suppressing
    the report: the user asked for analysis, so they get it, with its caveats.
    """
    warnings: list[str] = []
    freshness = freshness or {}

    if not getattr(dcf_result, "rf_is_live", True):
        warnings.append(
            "Risk-free rate is a hardcoded fallback, not a live quote — "
            "cost of equity and therefore intrinsic value may be off."
        )

    age = freshness.get("age_days")
    if age is None and freshness:
        warnings.append("No cached fundamentals found for this company.")
    elif age is not None and age > 90:
        warnings.append(
            f"Fundamentals are {age:.0f} days old — at least one quarterly result "
            f"has likely been published since. Run: python main.py cache --refresh"
        )

    if getattr(dcf_result, "verdict", "") == "INSUFFICIENT_DATA":
        warnings.append("Valuation could not be computed from the available data.")

    return (not warnings), warnings
